def _scalar_sys_witness(unit: AslUnit, overrides: dict[str, int]) -> tuple[int, int]:
    """Return one legal owner witness with explicit field overrides."""

    catalog = _catalog(unit)
    if len(catalog) != 1:
        raise ValueError(f"{unit.source_path}: SYS owner must own one form")
    _, record = catalog[0]
    instruction = encoded_catalog_witnesses([record])[0]
    fields = {field["name"] for field in record.get("fields", [])}
    for field, value in overrides.items():
        if field in fields:
            instruction = encode_field(record, field, instruction, value)
    length = record.get("length_bits")
    if not isinstance(length, int):
        raise ValueError(f"{unit.source_path}: SYS owner has no instruction length")
    return instruction, length


def _scalar_sys_setup(kind: str = "System") -> list[str]:
    """Return readable setup for one scalar body instruction."""

    return [
        "    ResetProfileState();",
        "    SetCurrentACR(0);",
        "    WriteTPC(Zeros{PTO_XLEN} + 0x100);",
        f"    BeginBundle(BundleKind_{kind}, BundleTransfer_Fallthrough,",
        "        Zeros{PTO_XLEN}, Zeros{PTO_XLEN} + 0x180,",
        "        Zeros{PTO_XLEN}, FALSE);",
        "    EnterBundleBody();",
    ]


def _scalar_sys_source_setup(selector: int, value: int) -> list[str]:
    """Initialize one complete Reg5 source without consuming a queue."""

    if selector < 24:
        return [f"    WriteGPR({selector}, Zeros{{PTO_XLEN}} + 0x{value:x});"]
    if selector < 28:
        index = selector - 24
        return [
            f"    _TQueue[[{index}]] = Zeros{{PTO_XLEN}} + 0x{value:x};",
            f"    _TQueueValid[[{index}]] = TRUE;",
        ]
    index = selector - 28
    return [
        f"    _UQueue[[{index}]] = Zeros{{PTO_XLEN}} + 0x{value:x};",
        f"    _UQueueValid[[{index}]] = TRUE;",
    ]


def _scalar_sys_source_expression(selector: int) -> str:
    if selector < 24:
        return f"ReadGPR({selector})"
    if selector < 28:
        return f"ReadTemporaryQueue(TRUE, {selector - 24})"
    return f"ReadTemporaryQueue(FALSE, {selector - 28})"


def _scalar_sys_destination_assertions(selector: int, value: int) -> list[str]:
    """Observe one complete Reg5 destination form after execution."""

    expected = f"Zeros{{PTO_XLEN}} + 0x{value:x}"
    if selector < 24:
        return [f"    assert ReadGPR({selector}) == {expected};"]
    if selector < 30:
        return [
            "    assert !_TQueueValid[[0]];",
            "    assert !_UQueueValid[[0]];",
        ]
    if selector == 30:
        return [
            "    assert _UQueueValid[[0]];",
            f"    assert ReadTemporaryQueue(FALSE, 0) == {expected};",
        ]
    return [
        "    assert _TQueueValid[[0]];",
        f"    assert ReadTemporaryQueue(TRUE, 0) == {expected};",
    ]


