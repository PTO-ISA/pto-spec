def sanitize(value: str, *, separator: str = "-") -> str:
    """Return one stable uppercase ASCII identifier component."""

    return re.sub(r"[^A-Z0-9]+", separator, value.upper()).strip(separator)


def asl_identifier(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "_", value).strip("_")


def bit_literal(value: int, width: int) -> str:
    if value < 0 or value >= 1 << width:
        raise ValueError(f"value {value} does not fit bits({width})")
    return "'" + format(value, f"0{width}b") + "'"


def _test_metadata(unit: AslUnit, test_id: str, kind: str) -> str:
    metadata = {
        "id": test_id,
        "source": unit.source_path.as_posix(),
        "requirements": [instruction_clause_id(unit.surface, unit.mnemonic or "")],
        "kind": kind,
        "summary": f"canonical {unit.mnemonic} catalog and ASL contract remain aligned",
        "pass_condition": "all canonical decode and contract assertions hold",
        "related_sources": [],
    }
    return json.dumps(metadata, separators=(",", ":"))


def _catalog(unit: AslUnit) -> tuple[tuple[int, dict[str, object]], ...]:
    indices = unit.metadata.get("catalog_indices")
    records = unit.metadata.get("catalog_records")
    if (
        not isinstance(indices, list)
        or not isinstance(records, list)
        or len(indices) != len(records)
    ):
        raise ValueError(f"{unit.source_path}: invalid catalog index/record metadata")
    if not indices:
        if unit.metadata.get("alias_of") and not records:
            return ()
        raise ValueError(f"{unit.source_path}: empty catalog ownership")
    paired: list[tuple[int, dict[str, object]]] = []
    for index, record in zip(indices, records, strict=True):
        if not isinstance(index, int) or not isinstance(record, dict):
            raise ValueError(f"{unit.source_path}: invalid catalog index/record entry")
        paired.append((index, record))
    return tuple(paired)


def _scalar_assertions(
    unit: AslUnit, witness_by_index: dict[int, int] | None = None
) -> list[str]:
    mnemonic = asl_identifier(unit.mnemonic or "")
    lines: list[str] = []
    catalog = _catalog(unit)
    witnesses = (
        encoded_catalog_witnesses([record for _, record in catalog])
        if witness_by_index is None
        else [witness_by_index[index] for index, _ in catalog]
    )
    for instruction, (index, record) in zip(witnesses, catalog, strict=True):
        length = record.get("length_bits")
        handler = record.get("semantic_handler")
        if not isinstance(length, int) or not isinstance(handler, str):
            raise ValueError(f"{unit.source_path}: invalid scalar length/handler")
        lines.extend(
            (
                f"    assert DecodeScalarForm({bit_literal(instruction, 48)}, {length}) == {index};",
                f"    assert ScalarOperationOfForm({index}) == ScalarOperation_{mnemonic};",
                f"    assert ScalarHandlerOfForm({index}) == ScalarHandler_{handler};",
                f"    assert InstructionContractOperation_{mnemonic}() == ScalarOperation_{mnemonic};",
                f"    assert InstructionContractHandler_{mnemonic}() == ScalarHandler_{handler};",
            )
        )
        if record.get("semantic_family") == "AGU":
            agu = record.get("agu")
            if not isinstance(agu, dict):
                raise ValueError(f"{unit.source_path}: AGU record lacks owner semantics")
            signed_load = "TRUE" if agu.get("signed_load") is True else "FALSE"
            returns_address = (
                "TRUE" if agu.get("prefetch_returns_address") is True else "FALSE"
            )
            lines.extend(
                (
                    f"    assert InstructionContractAGUAction_{mnemonic}() "
                    f"== ScalarAGU_{agu['action']};",
                    f"    assert InstructionContractAGUAddressKind_{mnemonic}() "
                    f"== ScalarAGU_{agu['address_kind']};",
                    f"    assert InstructionContractAGUSizeBytes_{mnemonic}() "
                    f"== {agu['size_bytes']};",
                    f"    assert InstructionContractAGUOffsetScale_{mnemonic}() "
                    f"== {agu['offset_scale']};",
                    f"    assert InstructionContractAGUUpdateMode_{mnemonic}() "
                    f"== AddressUpdate_{agu['update_mode']};",
                    f"    assert InstructionContractAGUSignedLoad_{mnemonic}() "
                    f"== {signed_load};",
                    f"    assert InstructionContractAGUPrefetchReturnsAddress_{mnemonic}() "
                    f"== {returns_address};",
                )
            )
        fields = record.get("fields", [])
        if not isinstance(fields, list):
            raise ValueError(f"{unit.source_path}: scalar fields must be an array")
        for field in fields:
            if not isinstance(field, dict):
                raise ValueError(f"{unit.source_path}: scalar field must be an object")
            name = field.get("name")
            pieces = field.get("pieces")
            if not isinstance(name, str) or not isinstance(pieces, list):
                raise ValueError(f"{unit.source_path}: invalid scalar field metadata")
            expected = 0
            for piece in pieces:
                if not isinstance(piece, dict) or any(
                    not isinstance(piece.get(key), int)
                    for key in ("instruction_lsb", "value_lsb", "width")
                ):
                    raise ValueError(f"{unit.source_path}: invalid scalar field piece")
                width = piece["width"]
                raw = (instruction >> piece["instruction_lsb"]) & ((1 << width) - 1)
                expected |= raw << piece["value_lsb"]
            lines.append(
                "    assert DecodeScalarOperandRaw("
                f"{bit_literal(instruction, 48)}, {index}, ScalarField_{name}) "
                f"== {bit_literal(expected, 48)};"
            )
    return lines


def _block_assertions(
    unit: AslUnit,
    witness_by_index: dict[int, int] | None = None,
    alias_target: AslUnit | None = None,
    source_text: str | None = None,
) -> list[str]:
    mnemonic = asl_identifier(unit.mnemonic or "")
    lines: list[str] = []
    catalog = _catalog(alias_target) if alias_target is not None else _catalog(unit)
    witnesses = (
        encoded_catalog_witnesses([record for _, record in catalog])
        if witness_by_index is None
        else [witness_by_index[index] for index, _ in catalog]
    )
    for instruction, (index, record) in zip(witnesses, catalog, strict=True):
        length = record.get("length_bits")
        form_id = record.get("form_id")
        handler = record.get("semantic_handler")
        if (
            not isinstance(length, int)
            or not isinstance(form_id, str)
            or not isinstance(handler, str)
        ):
            raise ValueError(f"{unit.source_path}: invalid block catalog contract")
        lines.extend(
            (
                f"    assert DecodeCommandForm({bit_literal(instruction, 64)}, {length}) == {index};",
                f"    assert CommandOperationOfForm({index}) == CommandOperation_{form_id};",
                f"    assert CommandHandlerOfForm({index}) == CommandHandler_{handler};",
                f"    assert InstructionContractMatches_{mnemonic}(CommandOperationOfForm({index}));",
                f"    assert InstructionContractHandler_{mnemonic}() == CommandHandler_{handler};",
            )
        )
    alias_engine = unit.metadata.get("alias_engine")
    if alias_target is not None:
        if alias_engine not in {"VEC", "SFU"}:
            raise ValueError(f"{unit.source_path}: invalid Block alias engine")
        lines.append(
            f"    assert InstructionContractAliasEngine_{mnemonic}() == "
            f"TileEngine_{alias_engine};"
        )
    contract = unit.metadata.get("contract", {})
    if not isinstance(contract, dict):
        raise ValueError(f"{unit.source_path}: block contract must be an object")
    cube_keys = CUBE_AVS_CONTRACT_KEYS.intersection(contract)
    if not cube_keys and source_text is not None:
        helper_patterns = {
            "tile_operation": (
                rf"readonly\s+func\s+InstructionContractTileOperation_{mnemonic}\(\)"
                rf"\s*=>\s*TileOperation\s*begin\s*return\s+TileOperation_"
                rf"([A-Za-z0-9_]+);\s*end;"
            ),
            "cube_function": (
                rf"readonly\s+func\s+InstructionContractCubeFunction_{mnemonic}\(\)"
                rf"\s*=>\s*integer\s*\{{0\.\.31\}}\s*begin\s*return\s+"
                rf"([0-9]+);\s*end;"
            ),
            "shared_operands_allowed": (
                rf"readonly\s+func\s+InstructionContractSharedOperandsAllowed_"
                rf"{mnemonic}\(\)\s*=>\s*boolean\s*begin\s*return\s+"
                rf"(TRUE|FALSE);\s*end;"
            ),
        }
        matches = {
            key: re.search(pattern, source_text, flags=re.MULTILINE)
            for key, pattern in helper_patterns.items()
        }
        if any(match is not None for match in matches.values()):
            missing_helpers = sorted(
                key for key, match in matches.items() if match is None
            )
            if missing_helpers:
                raise ValueError(
                    f"{unit.source_path}: incomplete CUBE AVS helpers; missing "
                    + ", ".join(missing_helpers)
                )
            contract = {
                "tile_operation": matches["tile_operation"].group(1),
                "cube_function": int(matches["cube_function"].group(1)),
                "shared_operands_allowed": (
                    matches["shared_operands_allowed"].group(1) == "TRUE"
                ),
            }
            cube_keys = CUBE_AVS_CONTRACT_KEYS.copy()
    if cube_keys:
        if cube_keys != CUBE_AVS_CONTRACT_KEYS:
            missing = sorted(CUBE_AVS_CONTRACT_KEYS - cube_keys)
            raise ValueError(
                f"{unit.source_path}: incomplete CUBE AVS contract; missing "
                + ", ".join(missing)
            )
        tile_operation = contract["tile_operation"]
        cube_function = contract["cube_function"]
        shared_operands_allowed = contract["shared_operands_allowed"]
        if not isinstance(tile_operation, str) or not tile_operation:
            raise ValueError(f"{unit.source_path}: invalid CUBE tile operation")
        if type(cube_function) is not int or not 0 <= cube_function <= 31:
            raise ValueError(f"{unit.source_path}: invalid CUBE function")
        if not isinstance(shared_operands_allowed, bool):
            raise ValueError(f"{unit.source_path}: invalid CUBE Shared policy")
        lines.extend(
            (
                f"    assert InstructionContractTileOperation_{mnemonic}() == "
                f"TileOperation_{tile_operation};",
                f"    assert InstructionContractCubeFunction_{mnemonic}() == "
                f"{cube_function};",
                f"    assert InstructionContractSharedOperandsAllowed_{mnemonic}() == "
                f"{'TRUE' if shared_operands_allowed else 'FALSE'};",
            )
        )
    return lines


def _tile_assertions(unit: AslUnit, source_text: str | None = None) -> list[str]:
    mnemonic = asl_identifier(unit.mnemonic or "")
    lines = [f"    // classification: {'/'.join(unit.classification)}"]
    block = unit.metadata.get("block", [])
    if not isinstance(block, list) or any(not isinstance(item, str) for item in block):
        raise ValueError(f"{unit.source_path}: tile block composition must be an array")
    lines.append(f"    // block: {' | '.join(block)}")
    catalog = _catalog(unit)
    for index, record in catalog:
        family = record.get("family")
        selector = record.get("selector")
        handler = record.get("semantic_handler")
        classification = unit.classification[0]
        engine = unit.metadata.get("engine")
        if not isinstance(family, str) or not isinstance(handler, str):
            raise ValueError(f"{unit.source_path}: invalid tile family/handler")
        if classification not in TILE_CLASS_ENUM:
            raise ValueError(f"{unit.source_path}: invalid Tile classification")
        if engine not in TILE_ENGINES:
            raise ValueError(f"{unit.source_path}: invalid Tile engine")
        if isinstance(selector, str):
            code = int(selector, 16)
        elif isinstance(record.get("function"), int):
            mode = record.get("mode", 0)
            if not isinstance(mode, int):
                raise ValueError(f"{unit.source_path}: tile mode is invalid")
            code = (mode << 10) | record["function"]
        else:
            raise ValueError(f"{unit.source_path}: tile selector is absent")
        lines.extend(
            (
                f"    assert DecodeTileOperation(TileDecode_{family}, {bit_literal(code, 12)}) == {index};",
                f"    assert TileOperationOfIndex({index}) == TileOperation_{mnemonic};",
                f"    assert TileHandlerOfIndex({index}) == TileHandler_{handler};",
                f"    assert TileClassOfIndex({index}) == {TILE_CLASS_ENUM[classification]};",
                f"    assert TileEngineOfIndex({index}) == TileEngine_{engine};",
                f"    assert InstructionContractOperation_{mnemonic}() == TileOperation_{mnemonic};",
                f"    assert InstructionContractHandler_{mnemonic}() == TileHandler_{handler};",
            )
        )
    if source_text is not None:
        function_match = re.search(
            rf"readonly\s+func\s+InstructionContractCubeFunction_{mnemonic}\(\)"
            rf"\s*=>\s*integer\s*\{{0\.\.31\}}\s*begin\s*return\s+"
            rf"([0-9]+);\s*end;",
            source_text,
            flags=re.MULTILINE,
        )
        shared_match = re.search(
            rf"readonly\s+func\s+InstructionContractSharedOperandsAllowed_"
            rf"{mnemonic}\(\)\s*=>\s*boolean\s*begin\s*return\s+"
            rf"(TRUE|FALSE);\s*end;",
            source_text,
            flags=re.MULTILINE,
        )
        if (function_match is None) != (shared_match is None):
            raise ValueError(f"{unit.source_path}: incomplete CUBE Tile helpers")
        if function_match is not None and shared_match is not None:
            if len(catalog) != 1 or not isinstance(catalog[0][1].get("function"), int):
                raise ValueError(f"{unit.source_path}: invalid CUBE Tile catalog")
            expected_function = catalog[0][1]["function"]
            if int(function_match.group(1)) != expected_function:
                raise ValueError(
                    f"{unit.source_path}: CUBE function helper/catalog mismatch"
                )
            lines.extend(
                (
                    f"    assert InstructionContractCubeFunction_{mnemonic}() == "
                    f"{expected_function};",
                    f"    assert InstructionContractSharedOperandsAllowed_{mnemonic}() == "
                    f"{shared_match.group(1)};",
                )
            )
    return lines


def render_mnemonic_avs(
    unit: AslUnit,
    scalar_witnesses: dict[int, int] | None = None,
    block_witnesses: dict[int, int] | None = None,
    alias_target: AslUnit | None = None,
    source_text: str | None = None,
) -> tuple[Path, str]:
    """Render the canonical checked-in AVS point for one mnemonic unit."""

    if unit.mnemonic is None or unit.surface not in {"scalar", "block", "tile"}:
        raise ValueError(
            f"{unit.source_path}: mnemonic AVS requires scalar, block, or tile instruction"
        )
    mnemonic = sanitize(unit.mnemonic)
    filename_mnemonic = mnemonic.lower()
    kind_slug = "STATIC" if unit.surface == "tile" else "DECODE"
    kind = "static-invariant" if unit.surface == "tile" else "decode-positive"
    test_id = f"PTO-AVS-{unit.surface.upper()}-{mnemonic}-{kind_slug}-001"
    path = (
        Path("tests/asl")
        / unit.source_path.relative_to("asl").with_suffix("")
        / (
            f"{unit.surface}-static-{filename_mnemonic}-contract-001.asl"
            if unit.surface == "tile"
            else f"{unit.surface}-decode-{filename_mnemonic}-canonical-001.asl"
        )
    )
    if unit.surface == "scalar":
        assertions = _scalar_assertions(unit, scalar_witnesses)
    elif unit.surface == "block":
        assertions = _block_assertions(
            unit,
            block_witnesses,
            alias_target,
            source_text,
        )
    else:
        assertions = _tile_assertions(unit, source_text)
    document = "\n".join(
        (
            GENERATED_MARKER,
            f"// PTO-TEST: {_test_metadata(unit, test_id, kind)}",
            "func main() => integer",
            "begin",
            *assertions,
            "    return 0;",
            "end;",
            "",
        )
    )
    return path, document


def render_block_alias_avs(
    unit: AslUnit,
    units: Sequence[AslUnit],
) -> list[tuple[Path, str]]:
    """Render the complete assigned-operation partition for one engine alias."""

    if unit.surface != "block" or unit.mnemonic is None:
        raise ValueError(f"{unit.source_path}: engine alias must be a Block mnemonic")
    alias_engine = unit.metadata.get("alias_engine")
    if alias_engine not in {"VEC", "SFU"}:
        return []

    operation_partition: list[tuple[int, str]] = []
    for operation_unit in units:
        if operation_unit.surface != "tile" or operation_unit.mnemonic is None:
            continue
        engine = operation_unit.metadata.get("engine")
        indices = operation_unit.metadata.get("catalog_indices")
        if not isinstance(engine, str) or not isinstance(indices, list):
            raise ValueError(
                f"{operation_unit.source_path}: Tile operation lacks engine or index"
            )
        for index in indices:
            if not isinstance(index, int):
                raise ValueError(
                    f"{operation_unit.source_path}: Tile operation index must be an integer"
                )
            operation_partition.append((index, engine))
    operation_partition.sort()
    if not operation_partition:
        raise ValueError(f"{unit.source_path}: engine alias has no Tile operations")
    if not any(engine == alias_engine for _, engine in operation_partition):
        raise ValueError(f"{unit.source_path}: engine alias accepts no Tile operation")
    if not any(engine != alias_engine for _, engine in operation_partition):
        raise ValueError(f"{unit.source_path}: engine alias has no rejection witness")

    mnemonic = sanitize(unit.mnemonic)
    identifier = asl_identifier(unit.mnemonic)
    test_id = f"PTO-AVS-BLOCK-{mnemonic}-ENGINE-001"
    path = (
        Path("tests/asl")
        / unit.source_path.relative_to("asl").with_suffix("")
        / f"block-bound-{mnemonic.lower()}-engine-001.asl"
    )
    metadata = {
        "id": test_id,
        "source": unit.source_path.as_posix(),
        "requirements": [instruction_clause_id(unit.surface, unit.mnemonic)],
        "kind": "boundary",
        "summary": (
            f"{unit.mnemonic} accepts exactly the assigned {alias_engine} operations"
        ),
        "pass_condition": (
            "every assigned Tile operation is accepted exactly when its engine matches "
            f"{alias_engine}"
        ),
        "related_sources": ["asl/block/execution/BSTART.TEPL.asl"],
    }
    assertions = [
        f"    assert InstructionContractAcceptsTileOperation_{identifier}({index}) "
        f"== {'TRUE' if engine == alias_engine else 'FALSE'};"
        for index, engine in operation_partition
    ]
    document = "\n".join(
        (
            GENERATED_MARKER,
            f"// PTO-TEST: {json.dumps(metadata, separators=(',', ':'))}",
            "func main() => integer",
            "begin",
            *assertions,
            "    return 0;",
            "end;",
            "",
        )
    )
    return [(path, document)]


def render_scalar_agu_avs(unit: AslUnit) -> list[tuple[Path, str]]:
    """Render four independently runnable semantic points for one AGU owner."""

    if (
        unit.surface != "scalar"
        or unit.mnemonic is None
        or unit.classification != ("agu",)
    ):
        raise ValueError(f"{unit.source_path}: scalar AGU AVS requires one AGU owner")
    mnemonic = sanitize(unit.mnemonic)
    identifier = asl_identifier(unit.mnemonic)
    filename_mnemonic = mnemonic.lower()
    owner_directory = (
        Path("tests/asl") / unit.source_path.relative_to("asl").with_suffix("")
    )
    points = (
        (
            "EXEC",
            "execution",
            "exec",
            "direct",
            f"ValidateScalarAGUExecute_{identifier}",
            "executes the canonical address calculation and architectural effect",
        ),
        (
            "BOUND",
            "boundary",
            "bound",
            "address",
            f"ValidateScalarAGUBounds_{identifier}",
            "covers address fields, modifiers, limits, and wrap behavior",
        ),
        (
            "FAULT",
            "fault",
            "fault",
            "precise",
            f"ValidateScalarAGUFault_{identifier}",
            "rejects faults before partial register or memory effects and reissues precisely",
        ),
        (
            "ALIAS",
            "execution",
            "exec",
            "registers",
            f"ValidateScalarAGUAlias_{identifier}",
            "covers absolute and temporary register selector aliases",
        ),
    )
    documents: list[tuple[Path, str]] = []
    for id_kind, kind, file_type, behavior, entrypoint, summary in points:
        test_id = f"PTO-AVS-AGU-{mnemonic}-{id_kind}-001"
        metadata = {
            "id": test_id,
            "source": unit.source_path.as_posix(),
            "requirements": [instruction_clause_id("scalar", unit.mnemonic)],
            "kind": kind,
            "summary": f"{unit.mnemonic} {summary}",
            "pass_condition": "the mnemonic-owned semantic assertions hold",
            "related_sources": [],
        }
        path = owner_directory / (
            f"scalar-{file_type}-{filename_mnemonic}-{behavior}-001.asl"
        )
        document = "\n".join(
            (
                GENERATED_MARKER,
                f"// PTO-TEST: {json.dumps(metadata, separators=(',', ':'))}",
                "func main() => integer",
                "begin",
                f"    {entrypoint}();",
                "    return 0;",
                "end;",
                "",
            )
        )
        documents.append((path, document))
    return documents


