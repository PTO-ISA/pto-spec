def render_concept_avs(root: Path, unit: AslUnit) -> tuple[Path, str]:
    """Render one compile/static-invariant point for a non-mnemonic ASL unit."""

    if unit.mnemonic is not None:
        raise ValueError(f"{unit.source_path}: concept AVS cannot own a mnemonic")
    identity = sanitize(unit.unit_id.removeprefix("PTO-"))
    test_id = f"PTO-AVS-{identity}-STATIC-001"
    if len(test_id) > 64:
        identity = identity.replace("CELL-REARRANGEMENT", "CELL-REARR")
        test_id = f"PTO-AVS-{identity}-STATIC-001"
    clauses = parse_ndf_regions(
        (root / unit.source_path).read_text(encoding="utf-8"), unit.source_path
    )
    model_harness = unit.unit_id in {
        "PTO-ARCH-DATA-TYPES-FUNCTIONAL-MODEL",
        "PTO-ARCH-DISPATCH-FUNCTIONAL-STEP",
        "PTO-ARCH-PROFILE-FUNCTIONAL-MODEL",
        "PTO-ARCH-STATE-FUNCTIONAL-MODEL",
    }
    metadata = {
        "id": test_id,
        "source": unit.source_path.as_posix(),
        "requirements": [clause.clause_id for clause in clauses],
        "kind": "static-invariant",
        "summary": (
            f"{unit.unit_id} compiles as a non-architectural model harness unit"
            if model_harness
            else f"{unit.unit_id} compiles as an independent normative unit"
        ),
        "pass_condition": (
            "the complete PTO model and this model-harness static invariant compile"
            if model_harness
            else "the complete model and this unit's static invariant compile"
        ),
        "related_sources": [],
    }
    concept_slug = sanitize(unit.source_path.stem).lower()
    path = (
        Path("tests/asl")
        / unit.source_path.relative_to("asl").with_suffix("")
        / f"{unit.surface}-static-{concept_slug}-contract-001.asl"
    )
    document = "\n".join(
        (
            GENERATED_MARKER,
            f"// PTO-TEST: {json.dumps(metadata, separators=(',', ':'))}",
            "func main() => integer",
            "begin",
            "    assert TRUE;",
            "    return 0;",
            "end;",
            "",
        )
    )
    return path, document


def generated_documents(root: Path) -> dict[Path, str]:
    units = load_units(root / "asl")
    scalar_catalog = sorted(
        (
            item
            for unit in units
            if unit.surface == "scalar" and unit.mnemonic is not None
            for item in _catalog(unit)
        ),
        key=lambda item: item[0],
    )
    if [index for index, _ in scalar_catalog] != list(range(len(scalar_catalog))):
        raise ValueError("scalar catalog indices are not contiguous")
    scalar_witnesses = dict(
        zip(
            (index for index, _ in scalar_catalog),
            encoded_catalog_witnesses([record for _, record in scalar_catalog]),
            strict=True,
        )
    )
    block_catalog = sorted(
        (
            item
            for unit in units
            if unit.surface == "block" and unit.mnemonic is not None
            for item in _catalog(unit)
        ),
        key=lambda item: item[0],
    )
    if [index for index, _ in block_catalog] != list(range(len(block_catalog))):
        raise ValueError("block catalog indices are not contiguous")
    block_witnesses = dict(
        zip(
            (index for index, _ in block_catalog),
            encoded_catalog_witnesses([record for _, record in block_catalog]),
            strict=True,
        )
    )
    by_mnemonic = {
        unit.mnemonic: unit for unit in units if unit.mnemonic is not None
    }
    documents: list[tuple[Path, str]] = []
    for unit in units:
        if unit.mnemonic is None:
            documents.append(render_concept_avs(root, unit))
            continue
        alias_of = unit.metadata.get("alias_of")
        alias_target = None
        if alias_of is not None:
            if not isinstance(alias_of, str) or alias_of not in by_mnemonic:
                raise ValueError(f"{unit.source_path}: unknown mnemonic alias target")
            alias_target = by_mnemonic[alias_of]
            if alias_target.metadata.get("alias_of") is not None:
                raise ValueError(f"{unit.source_path}: mnemonic alias chain is forbidden")
        documents.append(
            render_mnemonic_avs(
                unit,
                scalar_witnesses,
                block_witnesses,
                alias_target,
                (root / unit.source_path).read_text(encoding="utf-8"),
            )
        )
        if alias_target is not None:
            documents.extend(render_block_alias_avs(unit, units))
        if unit.surface == "scalar" and unit.classification == ("agu",):
            documents.extend(render_scalar_agu_avs(unit))
        if unit.surface == "scalar" and unit.classification == ("bru",):
            documents.extend(render_scalar_bru_avs(unit))
        if unit.surface == "scalar" and unit.classification == ("fsu",):
            documents.extend(render_scalar_fsu_avs(unit))
        if unit.surface == "scalar" and unit.classification == ("sys",):
            documents.extend(render_scalar_sys_avs(unit))
    by_path = dict(documents)
    if len(by_path) != len(documents):
        raise ValueError("mnemonic AVS path collision")
    return dict(sorted(by_path.items(), key=lambda item: item[0].as_posix()))


def _existing_generated(root: Path) -> set[Path]:
    test_root = root / "tests/asl"
    return (
        {
            path.relative_to(root)
            for path in test_root.rglob("*.asl")
            if path.read_text(encoding="utf-8").startswith(GENERATED_MARKER)
        }
        if test_root.exists()
        else set()
    )


def write_documents(root: Path, documents: dict[Path, str]) -> None:
    expected = set(documents)
    for stale in sorted(_existing_generated(root) - expected):
        (root / stale).unlink()
    for path, document in documents.items():
        absolute = root / path
        absolute.parent.mkdir(parents=True, exist_ok=True)
        absolute.write_text(document, encoding="utf-8")


def check_documents(root: Path, documents: dict[Path, str]) -> list[str]:
    errors: list[str] = []
    expected = set(documents)
    for stale in sorted(_existing_generated(root) - expected):
        errors.append(f"stale generated canonical AVS point: {stale}")
    for path, document in documents.items():
        absolute = root / path
        if not absolute.exists():
            errors.append(f"missing generated canonical AVS point: {path}")
        elif absolute.read_text(encoding="utf-8") != document:
            errors.append(f"stale generated canonical AVS point: {path}")
    return errors


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=ROOT)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    arguments = parser.parse_args(argv)
    root = arguments.root.resolve()
    try:
        documents = generated_documents(root)
        if arguments.write:
            write_documents(root, documents)
            print(f"wrote {len(documents)} canonical AVS points")
            return 0
        errors = check_documents(root, documents)
    except (OSError, ValueError) as error:
        errors = [str(error)]
    for error in errors:
        print(f"error: {error}", file=sys.stderr)
    if errors:
        return 1
    print(f"canonical AVS points are current: {len(documents)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
